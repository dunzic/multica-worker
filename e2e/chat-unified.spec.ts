import "./env";
import { test, expect } from "@playwright/test";
import { TestApiClient } from "./fixtures";

test.use({ channel: "chrome", viewport: { width: 1500, height: 1000 }, actionTimeout: 15_000, trace: "retain-on-failure" });

test("one chat list preserves direct/group drafts, deep links, topics and navigation", async ({ page }, info) => {
  test.setTimeout(180_000);
  const stamp = Date.now();
  const owner = new TestApiClient();
  const collaborator = new TestApiClient();
  await owner.login(`unified-owner-${stamp}@localhost`, "Collaboration owner");
  const ws = await owner.ensureWorkspace("Unified chat acceptance", `unified-${stamp}`);
  await owner.markUserOnboarded();
  const email = `unified-member-${stamp}@localhost`;
  await collaborator.login(email, "Quality partner");
  await collaborator.markUserOnboarded();
  await owner.addMemberByEmail(email);
  const partner = await collaborator.currentUserId();
  try {
    const direct = await owner.createChatSessionFixture();
    const group = await owner.createGroup("Quality review team", [partner]);
    const second = await owner.createGroup("Delivery follow-up team", [partner]);
    const initial = (await owner.groupTopics(group.id))[0] ?? await owner.createGroupTopic(group.id, "");
    const otherTopic = (await owner.groupTopics(second.id))[0] ?? await owner.createGroupTopic(second.id, "");
    await owner.sendGroupMessage(initial.id, "Quality evidence ready for shared review");
    await owner.sendGroupMessage(otherTopic.id, "Delivery checklist ready");
    await page.addInitScript((token) => {
      localStorage.setItem("multica_token", token!);
      localStorage.setItem("i18nextLng", "en");
      localStorage.setItem("multica:chat:isOpen", "false");
    }, owner.getToken());
    const chat = `/${ws.slug}/chat`;
    const oldLink = `${chat}/groups?conversation=${group.id}&topic=${initial.id}`;
    await page.goto(oldLink);
    await expect(page.getByRole("heading", { name: "Quality review team" })).toBeVisible();
    await expect(page.getByRole("link", { name: /Delivery follow-up team/ })).toBeVisible();
    await expect(page.getByText("E2E Chat Attachment Session", { exact: true })).toBeVisible();
    await expect(page.getByRole("navigation", { name: "Topics" })).toHaveCount(0);
    const editor = page.locator('[data-slot="chat-input-content"] [contenteditable="true"]');
    await editor.fill("Group draft remains in its own topic");
    await page.locator('input[type="file"][multiple]').last().setInputFiles({ name: "shared-review.txt", mimeType: "text/plain", buffer: Buffer.from("Synthetic shared review draft") });
    await expect(editor.locator(".file-card-node")).toHaveCount(1);
    await page.screenshot({ path: info.outputPath("mixed-list-group-draft.png") });
    await page.getByText("E2E Chat Attachment Session", { exact: true }).click();
    await expect(page).toHaveURL(`${chat}?session=${direct.id}`, { timeout: 15_000 });
    await expect(editor).not.toContainText("Group draft remains");
    await expect(editor.locator(".file-card-node")).toHaveCount(0);
    await editor.fill("Private direct draft remains separate");
    await page.getByRole("link", { name: /Quality review team/ }).click();
    await expect(editor).toContainText("Group draft remains in its own topic");
    await expect(editor.locator(".file-card-node")).toHaveCount(1);
    await page.goBack();
    await expect(page).toHaveURL(`${chat}?session=${direct.id}`);
    await expect(editor).toContainText("Private direct draft remains separate");
    await page.goForward();
    await expect(editor).toContainText("Group draft remains in its own topic");
    await page.reload();
    await expect(editor).toContainText("Group draft remains in its own topic");
    // Leave while an upload is pending. Its eventual write-back belongs to A,
    // never to B's live composer, and remains available when A is reopened.
    let finishUpload!: () => void;
    let markStarted!: () => void;
    const uploadRelease = new Promise<void>((resolve) => { finishUpload = resolve; });
    const uploadStarted = new Promise<void>((resolve) => { markStarted = resolve; });
    await page.route("**/api/upload-file", async (route) => { markStarted(); await uploadRelease; await route.continue(); });
    await page.locator('input[type="file"][multiple]').last().setInputFiles({ name: "pending-review.txt", mimeType: "text/plain", buffer: Buffer.from("Synthetic pending draft attachment") });
    await uploadStarted;
    await page.getByRole("link", { name: /Delivery follow-up team/ }).click();
    await expect(page.getByRole("heading", { name: "Delivery follow-up team" })).toBeVisible();
    await expect(editor).not.toContainText("Group draft remains");
    await expect(editor.locator(".file-card-node")).toHaveCount(0);
    const uploaded = page.waitForResponse((response) => response.url().endsWith("/api/upload-file") && response.ok());
    finishUpload();
    await uploaded;
    await page.unroute("**/api/upload-file");
    await page.getByRole("link", { name: /Quality review team/ }).click();
    await expect(editor.locator(".file-card-node")).toHaveCount(2);
    await expect(editor).toContainText("pending-review.txt");
    await page.screenshot({ path: info.outputPath("pending-upload-returned-to-source-draft.png") });
    // A plain group message never dispatches an agent.
    await editor.click();
    await page.keyboard.press("ControlOrMeta+a");
    await page.keyboard.press("Backspace");
    await expect(editor.locator(".file-card-node")).toHaveCount(0);
    await page.keyboard.insertText("Shared quality follow-up saved from the browser");
    await expect(editor).toHaveText("Shared quality follow-up saved from the browser");
    await page.getByRole("button", { name: "Send", exact: true }).click();
    await expect(page.locator("article").getByText("Shared quality follow-up saved from the browser", { exact: true })).toBeVisible();
    await expect(editor).toHaveText("");
    await expect(page.getByRole("link", { name: /Quality review team/ })).toContainText("Shared quality follow-up saved");
    await page.getByRole("button", { name: "New topic", exact: true }).click();
    await expect(page.getByRole("link", { name: "Topic 2", exact: true })).toHaveAttribute("aria-current", "page");
    await editor.fill("Second topic draft");
    await page.getByRole("link", { name: "Topic 1", exact: true }).click();
    await expect(editor).not.toContainText("Second topic draft");
    await page.getByRole("link", { name: "Topic 2", exact: true }).click();
    await expect(editor).toContainText("Second topic draft");
    await page.screenshot({ path: info.outputPath("mixed-list-topic-navigation.png") });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "Chat", exact: true }).click();
    await expect(page.getByRole("link", { name: /Quality review team/ })).toBeVisible();
    await page.screenshot({ path: info.outputPath("mixed-list-narrow.png") });
    await page.getByRole("link", { name: /Quality review team/ }).focus();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("heading", { name: "Quality review team" })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("group-narrow-keyboard.png") });
    await page.setViewportSize({ width: 1500, height: 1000 });
    await page.getByRole("button", { name: "Create group", exact: true }).click();
    const create = page.getByRole("dialog", { name: "Create group", exact: true });
    await create.getByRole("textbox").fill("Shared delivery decisions");
    await create.getByRole("checkbox", { name: "Quality partner", exact: true }).check();
    const createPath = "**/api/v2/conversations";
    await page.route(createPath, (route) => route.request().method() === "POST" ? route.abort("internetdisconnected") : route.continue());
    await create.getByRole("button", { name: "Create group", exact: true }).click();
    await expect(create.getByRole("alert")).toBeVisible();
    await expect(create.getByRole("textbox")).toHaveValue("Shared delivery decisions");
    await expect(create.getByRole("checkbox", { name: "Quality partner", exact: true })).toBeChecked();
    await page.screenshot({ path: info.outputPath("group-create-failed-input-preserved.png") });
    await page.unroute(createPath);
    await create.getByRole("button", { name: "Create group", exact: true }).click();
    await expect(create).not.toBeVisible();
    await expect(page.getByRole("heading", { name: "Shared delivery decisions", exact: true })).toBeVisible();
    await expect(page.getByRole("link", { name: /Shared delivery decisions/ })).toHaveCount(1);
    await page.screenshot({ path: info.outputPath("new-group-in-unified-list.png") });
    await page.route(createPath, (route) => route.abort("internetdisconnected"));
    await page.reload();
    await expect(page.getByRole("button", { name: "Retry", exact: true }).first()).toBeVisible({ timeout: 20_000 });
    await expect(page.getByRole("heading", { name: "Shared delivery decisions", exact: true })).not.toBeVisible();
    await page.screenshot({ path: info.outputPath("group-list-failed.png") });
    await page.unroute(createPath);
    await page.getByRole("button", { name: "Retry", exact: true }).first().click();
    await expect(page.getByRole("heading", { name: "Shared delivery decisions", exact: true })).toBeVisible();
  } catch (error) {
    await page.screenshot({ path: info.outputPath("failure.png") }).catch(() => {});
    throw error;
  } finally {
    await owner.cleanup();
    await owner.deleteWorkspace();
  }
});
